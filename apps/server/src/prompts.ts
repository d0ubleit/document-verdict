/** Промпт для вердикта. Текст уже обезличен — ИИ не должен цитировать значения. */
export function buildVerdictPrompt(documentType: DocumentType, maskedText: string): string {
  return [
    'Ты — эксперт по проверке договоров для обычных людей. Текст документа ОБЕЗЛИЧЕН:',
    'персональные данные заменены на плейсхолдеры вида [ФИО], [ПАСПОРТ], [АДРЕС].',
    'Анализируй риски по категориям: ' + RISK_TAXONOMY.join(', ') + '.',
    'Особенности типа документа: ' + TYPE_NOTES[documentType],
    'Требования к ответу:',
    '- верни ТОЛЬКО JSON без пояснений, без markdown-обёртки;',
    '- score — целое число от 0 до 10 (0 — безопасно, 10 — крайне рискованно);',
    '- trafficLight: "green" (0-3), "yellow" (4-6), "red" (7-10);',
    '- risks — массив объектов {severity: "low"|"medium"|"high", clause: ссылка на пункт, description: риск простым языком, action: что сделать};',
    '- recommendation — общая рекомендация простым языком;',
    '- НЕ цитируй суммы, даты и иные значения — ссылайся на пункты и плейсхолдеры.',
    '',
    'Документ:',
    maskedText,
  ].join('\n');
}
