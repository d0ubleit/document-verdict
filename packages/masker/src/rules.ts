import type { PlaceholderType } from './types.ts';
import { hasContextNear } from './protect.ts';

/**
 * Правила маскирования под РФ-форматы.
 * Каждое правило: тип + регулярное выражение + опциональный контекстный тест.
 * Правила намеренно консервативны: лучше недомаскировать и показать пользователю
 * экран «подтвердите замены», чем помаскировать суммы и даты договора.
 */

export interface Rule {
  type: PlaceholderType;
  name: string;
  pattern: RegExp;
  /** Дополнительная проверка: (match, fullText) => boolean */
  test?: (m: RegExpExecArray, fullText: string) => boolean;
  /** true — правило работает только в агрессивном режиме. */
  aggressiveOnly?: boolean;
}

const PASSPORT_CONTEXT = /(паспорт|паспорта|паспортом|удостоверени|серия|выдан|удостоверяет)/iu;
const DOB_CONTEXT = /(рождени|родился|родилась|год рождения|г\.р\.)/iu;
/**
 * Контекст человека для трёхсловного правила ФИО: без него правило даёт
 * ложные срабатывания на названиях организаций («Центр правовых знаний»,
 * «Школа Катерины Ромашкиной»). Полные ФИО почти всегда стоят после
 * ролевой подписи («Исполнитель:», «в лице директора», «Гражданин»).
 */
const PERSON_CONTEXT =
  /(гражданин|гражданка|гр\.|в лице|именуем|действующ|паспорт|зарегистрирован|проживающ|подписал|доверяю|уполномочиваю|фамилия|займодавец|заёмщик|арендодатель|арендатор|продавец|покупатель|исполнитель|заказчик|подрядчик|работник|работодатель|доверитель|представитель|страхователь|страховщик|выгодоприобретатель|предпринимател|директор|руководител|генеральн)/iu;

/**
 * Ролевые/организационные слова, с которых трёхсловное правило ФИО НЕ должно
 * начинаться: «Гражданин Иванов Евгений» — не имя, а «Иванов Евгений
 * Иванович» — имя. Без этого списка matchAll съедает неверный span, и
 * правильный (со сдвигом) уже не находится. \b не работает с кириллицей —
 * используем Unicode-лукараунд.
 */
export const NAME_FIRST_WORD_BLOCK =
  /(?:гражданин|гражданка[\p{L}\p{N}_]*|индивидуальный[\p{L}\p{N}_]*|предприниматель[\p{L}\p{N}_]*|общество[\p{L}\p{N}_]*|фонд[\p{L}\p{N}_]*|центр[\p{L}\p{N}_]*|школа[\p{L}\p{N}_]*|компания[\p{L}\p{N}_]*|фирма[\p{L}\p{N}_]*|ассоциация[\p{L}\p{N}_]*|организация[\p{L}\p{N}_]*|агентство[\p{L}\p{N}_]*|университет[\p{L}\p{N}_]*|институт[\p{L}\p{N}_]*|академия[\p{L}\p{N}_]*|министерство[\p{L}\p{N}_]*|департамент[\p{L}\p{N}_]*|управление[\p{L}\p{N}_]*|администрация[\p{L}\p{N}_]*|правительство[\p{L}\p{N}_]*|президент[\p{L}\p{N}_]*|банк[\p{L}\p{N}_]*|кодекс[\p{L}\p{N}_]*|закон[\p{L}\p{N}_]*|договор[\p{L}\p{N}_]*|соглашение[\p{L}\p{N}_]*|приложение[\p{L}\p{N}_]*|раздел[\p{L}\p{N}_]*|глава[\p{L}\p{N}_]*|пункт[\p{L}\p{N}_]*|статья[\p{L}\p{N}_]*|часть[\p{L}\p{N}_]*|российск[\p{L}\p{N}_]*|федераци[\p{L}\p{N}_]*|област[\p{L}\p{N}_]*|республик[\p{L}\p{N}_]*|москв[\p{L}\p{N}_]*|санкт-петербург[\p{L}\p{N}_]*|совет[\p{L}\p{N}_]*|комитет[\p{L}\p{N}_]*|служба[\p{L}\p{N}_]*|инспекци[\p{L}\p{N}_]*|прокуратур[\p{L}\p{N}_]*|суд[\p{L}\p{N}_]*|арбитраж[\p{L}\p{N}_]*|нотариус[\p{L}\p{N}_]*|председател[\p{L}\p{N}_]*|генеральн[\p{L}\p{N}_]*|директор[\p{L}\p{N}_]*|руководител[\p{L}\p{N}_]*|начальник[\p{L}\p{N}_]*|заместител[\p{L}\p{N}_]*|главн[\p{L}\p{N}_]*|ведущ[\p{L}\p{N}_]*|старш[\p{L}\p{N}_]*|перв[\p{L}\p{N}_]*|продав[\p{L}\p{N}_]*|покупател[\p{L}\p{N}_]*|страховщик[\p{L}\p{N}_]*|страховател[\p{L}\p{N}_]*|выгодоприобретател[\p{L}\p{N}_]*|заказчик[\p{L}\p{N}_]*|исполнител[\p{L}\p{N}_]*|подрядчик[\p{L}\p{N}_]*|арендатор[\p{L}\p{N}_]*|арендодател[\p{L}\p{N}_]*|работник[\p{L}\p{N}_]*|работодател[\p{L}\p{N}_]*|займодавец[\p{L}\p{N}_]*|заёмщик[\p{L}\p{N}_]*|заемщик[\p{L}\p{N}_]*|доверител[\p{L}\p{N}_]*|представител[\p{L}\p{N}_]*|подпис[\p{L}\p{N}_]*|акцепт[\p{L}\p{N}_]*|перечен[\p{L}\p{N}_]*|обучающ[\p{L}\p{N}_]*|фамили[\p{L}\p{N}_]*|этап[\p{L}\p{N}_]*|срок[\p{L}\p{N}_]*|сторон[\p{L}\p{N}_]*|город[\p{L}\p{N}_]*|сумма[\p{L}\p{N}_]*|цена[\p{L}\p{N}_]*|адрес[\p{L}\p{N}_]*|реквизит[\p{L}\p{N}_]*|приказ[\p{L}\p{N}_]*|таблиц[\p{L}\p{N}_]*|граф[\p{L}\p{N}_]*|номер[\p{L}\p{N}_]*|дат[\p{L}\p{N}_]*|мест[\p{L}\p{N}_]*|лиц[\p{L}\p{N}_]*)(?![\p{L}\p{N}_])/iu;

/**
 * ВАЖНО: \b в JavaScript считает «словными» только ASCII-буквы/цифры —
 * перед кириллицей он не срабатывает. Поэтому для кириллических правил
 * используем Unicode-лукараунды: (?<![\p{L}\p{N}_]) … (?![\p{L}\p{N}_]).
 */
const WORD_B = '(?<![\\p{L}\\p{N}_])';
const WORD_E = '(?![\\p{L}\\p{N}_])';

export const RULES: Rule[] = [
  // Паспорт РФ: «серия 4508 № 123456», «4508 123456», «4508-123456»,
  // «серия 1234 номер 123456» — с контекстом.
  {
    type: 'PASSPORT',
    name: 'паспорт РФ',
    pattern: /\b\d{4}(?:\s*№\s*|\s+номер\s+|\s+|-)\d{6}\b/gu,
    test: (m, text) => hasContextNear(text, m.index, PASSPORT_CONTEXT, 70, 50),
  },
  // Паспорт с серией через пробел: «серия 45 08 № 123456», «45 08 123456».
  {
    type: 'PASSPORT',
    name: 'паспорт РФ (серия через пробел)',
    pattern: /\b\d{2}\s+\d{2}(?:\s*№\s*|\s+номер\s+|\s+|-)\d{6}\b/gu,
    test: (m, text) => hasContextNear(text, m.index, PASSPORT_CONTEXT, 70, 50),
  },
  // Слитный паспорт: «паспорт 4508123456» (серия+номер без пробела, 10 цифр).
  // Стоит ДО правила ИНН — при одинаковом span дедупликация оставит [ПАСПОРТ].
  {
    type: 'PASSPORT',
    name: 'паспорт РФ (слитный)',
    pattern: /\b\d{10}\b/gu,
    test: (m, text) => hasContextNear(text, m.index, PASSPORT_CONTEXT, 70, 50),
  },
  // Загранпаспорт: 2 буквы + 7 цифр (X1234567).
  {
    type: 'PASSPORT',
    name: 'загранпаспорт',
    pattern: new RegExp(`${WORD_B}[А-ЯЁA-Z]{2}\\d{7}${WORD_E}`, 'gu'),
  },

  // ИНН: 12 цифр (физлицо/ИП) или 10 (юрлицо) — маскируем оба (ИНН юрлица не нужен вердикту).
  { type: 'INN', name: 'ИНН', pattern: /(?<![\d])(?:\d{12}|\d{10})(?!\d)/gu },

  // ОГРНИП (15 цифр) — это ИП, т.е. физлицо в бизнесе: маскируем.
  { type: 'INN', name: 'ОГРНИП', pattern: /(?<![\d])\d{15}(?!\d)/gu },

  // СНИЛС: 123-456-789 01 и слитный 12345678901 (только с контекстом,
  // чтобы не спутать с телефоном из 11 цифр).
  { type: 'SNILS', name: 'СНИЛС', pattern: /\d{3}-\d{3}-\d{3}\s*\d{2}/gu },
  {
    type: 'SNILS',
    name: 'СНИЛС (слитный)',
    pattern: /\b\d{11}\b/gu,
    test: (m, text) =>
      hasContextNear(text, m.index, /(снилс|страхов|свидетельств|пенсионн)/iu, 40, 0),
  },

  // Телефоны: +7 916 123-45-67, 8 (916) 123-45-67, 89161234567.
  {
    type: 'PHONE',
    name: 'телефон',
    pattern: /(?<!\d)(?:\+?7|8)\s?\(?\d{3}\)?[\s-]?\d{3}[\s-]?\d{2}[\s-]?\d{2}(?!\d)/gu,
  },

  // Email.
  { type: 'EMAIL', name: 'email', pattern: /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/gu },

  // Расчётный счёт: 20 цифр.
  { type: 'ACCOUNT', name: 'расчётный счёт', pattern: /(?<![\d])\d{20}(?!\d)/gu },

  // Банковская карта: 16 цифр группами по 4.
  { type: 'ACCOUNT', name: 'карта', pattern: /\b\d{4}\s?\d{4}\s?\d{4}\s?\d{4}\b/gu },

  // Дата рождения — только с контекстом («дата рождения: 15.03.1985», «03.07.1988 г.р.»).
  {
    type: 'DOB',
    name: 'дата рождения',
    pattern: /\b\d{2}\.\d{2}\.\d{4}\b/gu,
    test: (m, text) => hasContextNear(text, m.index, DOB_CONTEXT, 40, 30),
  },

  // Дата выдачи документа: «паспорт 4508 123456, выдан 01.01.2010» —
  // часть паспортных данных («кем и когда выдан»).
  {
    type: 'DATE_ISSUE',
    name: 'дата выдачи',
    pattern: /\b\d{1,2}\.\d{1,2}\.\d{4}\b/gu,
    test: (m, text) =>
      hasContextNear(text, m.index, /(выдан|выдано|выдачи|выданн|когда выдан)/iu, 35, 0),
  },

  // Код подразделения: «код подразделения 770-123» — паспортные данные.
  {
    type: 'PASSPORT',
    name: 'код подразделения',
    pattern: /\b\d{3}-\d{3}\b/gu,
    test: (m, text) => hasContextNear(text, m.index, /(подразделения|код)/iu, 30, 0),
  },

  // ИП + фамилия: «ИП Иванов», «ИП Иванов Иван».
  {
    type: 'COMPANY',
    name: 'ИП-наименование',
    pattern: new RegExp(`${WORD_B}ИП\\s+[А-ЯЁ][а-яё]+(?:\\s+[А-ЯЁ][а-яё]+){0,1}${WORD_E}`, 'gu'),
  },

  // ФИО полностью: «Иванов Иван Иванович» — только с контекстом человека
  // (иначе маскируются названия организаций из трёх слов) и не начинается
  // с ролевого слова («Гражданин Иванов Евгений» — неверный span).
  // block.source теряет свой флаг i при встраивании — применяем (?i:...)
  // точечно к блоку, остальная часть паттерна остаётся регистрозависимой.
  {
    type: 'NAME',
    name: 'ФИО',
    pattern: new RegExp(
      `${WORD_B}(?!(?i:${NAME_FIRST_WORD_BLOCK.source}))[А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?\\s+[А-ЯЁ][а-яё]+\\s+[А-ЯЁ][а-яё]+${WORD_E}`,
      'gu',
    ),
    test: (m, text) => hasContextNear(text, m.index, PERSON_CONTEXT, 90, 0),
  },

  // ФИО с инициалами: «Иванов И.И.», «Иванов И.И», «Гаврилова Д.А»
  // (инициалы однозначны — контекст не требуется; финальная точка опциональна).
  {
    type: 'NAME',
    name: 'ФИО (инициалы)',
    pattern: new RegExp(`${WORD_B}[А-ЯЁ][а-яё]+\\s+[А-ЯЁ]\\.[А-ЯЁ]\\.?${WORD_E}`, 'gu'),
  },

  // «гр. Иванов», «гражданин Иванов И.И.». Полное ФИО из трёх слов после
  // «гражданина» маскирует правило «ФИО» (контекст тот же) — здесь берём
  // только фамилию (+инициалы), иначе «Иванович» остаётся непомаскированным.
  // «гражданин Российской Федерации» — не имя, отсекаем (\b с кириллицей
  // не работает — используем Unicode-лукараунд).
  {
    type: 'NAME',
    name: 'ФИО (гражданин)',
    pattern: new RegExp(
      `${WORD_B}(?:гр\\.|гражданин(?:ка)?)\\s+(?!Российск[\\p{L}\\p{N}_]*|России(?!\\p{L}))([А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?)(?!\\s+[А-ЯЁ][а-яё]+\\s+[А-ЯЁ][а-яё]+)(?:\\s+[А-ЯЁ]\\.[А-ЯЁ]\\.?)?${WORD_E}`,
      'gu',
    ),
  },

  // Подпись с повтором фамилии: «Иванов Иванов Е.И.» (реальные договоры;
  // normalize() схлопывает множественные пробелы в один).
  {
    type: 'NAME',
    name: 'ФИО (подпись: повтор фамилии)',
    pattern: new RegExp(`${WORD_B}([А-ЯЁ][а-яё]+)\\s+\\1\\s+[А-ЯЁ]\\.[А-ЯЁ]\\.?${WORD_E}`, 'gu'),
  },

  // Одиночная фамилия в подписи: «Подписал: Иванов». Только рядом с ролевым
  // контекстом, в позиции подписи (дальше — конец строки/текста или
  // пунктуация, а НЕ следующее слово), не после кавычки (название компании)
  // и не после «ООО/АО/ИП» (наименование юрлица). Роли отсекаются блок-списком.
  {
    type: 'NAME',
    name: 'ФИО (одиночная фамилия в подписи)',
    pattern: new RegExp(
      `${WORD_B}(?!(?i:${NAME_FIRST_WORD_BLOCK.source}))[А-ЯЁ][а-яё]+${WORD_E}`,
      'gu',
    ),
    test: (m, text) => {
      const lineStartIdx = text.lastIndexOf('\n', m.index - 1) + 1;
      const lineBefore = text.slice(lineStartIdx, m.index);
      const after = text.slice(m.index + m[0].length, m.index + m[0].length + 30);
      // Слово либо единственное на строке, либо следует за ролью в начале строки
      // («Подписал: Иванов») — в середине прозы не маскируем.
      // Роль-метка в начале строки перед фамилией («Подписал: Иванов»).
      // Вариант «слово одно на строке» убран: заголовки разделов («Оплата»,
      // «Услуги») тоже стоят одни на строке — слишком много ложных срабатываний.
      const signatureContext =
        /^(?:подпис|фамилия|исполнител|подрядчик|заказчик|арендатор|арендодатель|займодавец|заёмщик|заемщик|продавец|покупатель|работник|работодатель|в лице|доверител|представител|генеральн|директор|страхователь|страховщик)[а-яё]*:?\s*$/iu;
      const quotedBefore = /[«"']\s*$/u.test(lineBefore);
      const orgBefore = /(?:ООО|ОАО|ЗАО|ПАО|АО|ИП|ОО)\s+$/iu.test(lineBefore);
      const signaturePosition = /^\s*(\n|$|[.,;:!?)\]»"'«/])/u.test(after);
      return (
        lineBefore.length <= 40 &&
        signatureContext.test(lineBefore) &&
        !quotedBefore &&
        !orgBefore &&
        signaturePosition
      );
    },
  },

  // Адрес по улице: «ул. Ленина, д. 5, кв. 12», «ул Молодежная, дом 46»
  // (точка после «ул»/«г» опциональна — реальные договоры пишут без точек).
  {
    type: 'ADDRESS',
    name: 'адрес (улица)',
    pattern: new RegExp(
      `${WORD_B}(?:ул\\.?|улица|пр-т|проспект|пер\\.|переулок|б-р|бульвар|наб\\.|шоссе|ш\\.)\\s*[А-ЯЁа-яё\\-0-9]{2,60}(?:,?\\s*(?:д\\.|дом|кв\\.|квартира|корп\\.|стр\\.|оф\\.?|лит\\.)\\s*[\\d/А-ЯЁа-яё\\-]{1,12})*${WORD_E}`,
      'gu',
    ),
  },

  // Город: «г. Москва», «г Одинцово», «г.о. Одинцовский» — только если за ним
  // улица/дом ИЛИ перед ним адресный контекст («по адресу:»). Иначе
  // маскируются города в названиях органов («Управление ФАС по г. Москве»).
  {
    type: 'ADDRESS',
    name: 'адрес (город)',
    pattern: new RegExp(
      `${WORD_B}(?:г\\.о\\.?|г\\.?|гор\\.?|город|пгт|пос\\.|с\\.|село|дер\\.|деревня)\\s*[А-ЯЁ][А-ЯЁа-яё\\-]{2,40}${WORD_E}`,
      'gu',
    ),
    test: (m, text) => {
      const after = text.slice(m.index + m[0].length, m.index + m[0].length + 45);
      const before = text.slice(Math.max(0, m.index - 45), m.index);
      const streetAfter =
        /(?:ул\.?|улица|пр-т|проспект|пер\.|переулок|б-р|бульвар|наб\.|шоссе|ш\.|д\.|дом|кв\.|квартира|корп\.|стр\.)/iu;
      const addressContext =
        /(адрес|регистраци|прожива|зарегистрирован|прописан|место нахождения|местонахождение|рожден|уроженец|месторождени)/iu;
      return streetAfter.test(after) || addressContext.test(before);
    },
  },

  // «Кем выдан»: «выдан 08.05.2013г. УФМС России по гор. Москве по району
  // Ховрино» — орган, выдавший документ (часть паспортных данных).
  {
    type: 'ISSUED_BY',
    name: 'кем выдан',
    pattern: new RegExp(
      `${WORD_B}(?:УФМС|ФМС|УВД|ОВД|ГУВД|МВД|ОМВД|ОФМС|ОУФМС|отдел[\\p{L}\\p{N}_]*|управлени[\\p{L}\\p{N}_]*|паспортн[\\p{L}\\p{N}_]*\\s*стол[\\p{L}\\p{N}_]*|полици[\\p{L}\\p{N}_]*|служб[\\p{L}\\p{N}_]*)[^,;)\\n]{2,80}${WORD_E}`,
      'gu',
    ),
    test: (m, text) => hasContextNear(text, m.index, /(выдан|выдано|выдачи|выданн)/iu, 35, 0),
  },

  // Почтовый индекс (6 цифр) перед адресом — в агрессивном режиме.
  {
    type: 'ADDRESS',
    name: 'почтовый индекс',
    pattern: /\b\d{6}\b/gu,
    aggressiveOnly: true,
  },
];
