const SKIP_WORD = new RegExp(`^(?:${SKIP_STEMS.join('|')})[\\p{L}\\p{N}_]*$`, 'iu');

let hits = 0;
for (const dir of DIRS) {
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.txt'))) {
    const raw = readFileSync(join(dir, file), 'utf8');
    const doc = raw
      .split('\n')
      .filter((l) => !/^(EXPECT|KEEP|LEAK|NO_MASK):/.test(l))
      .join('\n');
    const masked = maskText(doc).maskedText;
    for (const [name, re] of PATTERNS) {
      for (const m of masked.matchAll(re)) {
        // Тройки, где любое слово — ролевое/официальное («Президента Российской
        // Федерации», «Стороны Договора обязаны») — не ПДн.
        if (name === 'ФИО (3 слова подряд)' && m[0].split(' ').some((w) => SKIP_WORD.test(w))) {
          continue;
        }
        const ctx = masked
          .slice(Math.max(0, m.index - 40), m.index + m[0].length + 40)
          .replace(/\n/g, ' ⏎ ');
        console.log(`[${name}] ${file}: …${ctx}…`);
        hits += 1;
      }
    }
  }
}
console.log(
  hits === 0
    ? '✅ Audit clean: no residual PII-like patterns found.'
    : `⚠️  ${hits} hits — review above.`,
);
